import type { Report } from './engine';

/** RFC 4180 CSV field. Also neutralises spreadsheet formula injection. */
function csvField(value: string): string {
  let v = value;
  if (/^[=+\-@\t\r]/.test(v) && !/^-?\d/.test(v)) v = `'${v}`;
  return /[",\r\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v;
}

const pad = (n: number) => String(n).padStart(2, '0');
function isoDate(d: Date): string {
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}

export function reportFilename(report: Report, ext: 'csv' | 'pdf'): string {
  const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  return `kitcount-${slug(report.templateId)}-${report.period.key}.${ext}`;
}

/** Machine-readable value: integers as-is, percents as numbers 0-100, blanks for unknown. */
function csvValue(row: Report['sections'][number]['rows'][number]): string {
  if (row.value === null || !Number.isFinite(row.value)) return '';
  if (row.display.endsWith('%')) return String(Math.round(row.value * 1000) / 10);
  if (Number.isInteger(row.value)) return String(row.value);
  return String(Math.round(row.value * 100) / 100);
}

export function reportToCsv(report: Report): string {
  const lastDay = new Date(report.period.end.getTime() - 1);
  const lines: string[][] = [
    ['Report', report.templateName],
    ['Jurisdiction', report.jurisdiction],
    ['Program', report.programName],
    ['Period', `${isoDate(report.period.start)} to ${isoDate(lastDay)}`],
    ['Generated', report.generatedAt.toISOString()],
    ['Template', `${report.templateId}${report.templateVersion ? ` v${report.templateVersion}` : ''}`],
    [],
    ['Section', 'Code', 'Item', 'Value'],
  ];
  for (const section of report.sections) {
    for (const row of section.rows) lines.push([section.title, row.code ?? '', row.label, csvValue(row)]);
  }
  return lines.map((l) => l.map(csvField).join(',')).join('\r\n') + '\r\n';
}

function esc(s: string): string {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

/** Print-ready HTML (rendered to PDF on device). */
export function reportToHtml(report: Report): string {
  const lastDay = new Date(report.period.end.getTime() - 1);
  const sections = report.sections
    .map(
      (s) => `
      <h2>${esc(s.title)}</h2>
      <table>
        <tbody>
          ${s.rows
            .map(
              (r) => `<tr>
                <td class="code">${esc(r.code ?? '')}</td>
                <td class="label">${esc(r.label)}${r.help ? `<div class="help">${esc(r.help)}</div>` : ''}</td>
                <td class="value">${esc(r.display)}${r.manual ? '<span class="tag">entered</span>' : ''}</td>
              </tr>`,
            )
            .join('')}
        </tbody>
      </table>`,
    )
    .join('');
  return `<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>${esc(report.templateName)} — ${esc(report.period.label)}</title>
<style>
  @page { margin: 18mm 16mm; }
  body { font-family: -apple-system, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; color: #10231f; font-size: 11pt; }
  header { border-bottom: 3px solid #0f766e; padding-bottom: 10px; margin-bottom: 8px; }
  h1 { font-size: 17pt; margin: 0 0 4px; }
  .meta { color: #43615a; font-size: 10pt; }
  h2 { font-size: 12pt; color: #0f766e; margin: 18px 0 6px; text-transform: uppercase; letter-spacing: .04em; }
  table { width: 100%; border-collapse: collapse; }
  td { border-bottom: 1px solid #d7e4e0; padding: 7px 6px; vertical-align: top; }
  td.code { width: 48px; color: #43615a; font-variant-numeric: tabular-nums; }
  td.value { width: 120px; text-align: right; font-weight: 700; font-variant-numeric: tabular-nums; }
  .help { color: #5d7771; font-size: 9pt; margin-top: 2px; }
  .tag { display: inline-block; margin-left: 6px; font-size: 7.5pt; font-weight: 600; color: #8a5a00; background: #fff4d6; border-radius: 4px; padding: 1px 4px; }
  footer { margin-top: 22px; color: #5d7771; font-size: 8.5pt; }
</style></head>
<body>
  <header>
    <h1>${esc(report.templateName)}</h1>
    <div class="meta">${esc(report.programName)} · ${esc(report.jurisdiction)} · ${esc(isoDate(report.period.start))} to ${esc(isoDate(lastDay))}</div>
  </header>
  ${sections}
  <footer>
    Generated by Kitcount on ${esc(report.generatedAt.toISOString())} from ${report.visitCount.toLocaleString('en-US')} encounters.
    Template ${esc(report.templateId)}${report.templateVersion ? ` v${esc(report.templateVersion)}` : ''}.
    ${report.disclaimer ? `<br>${esc(report.disclaimer)}` : ''}
  </footer>
</body></html>`;
}
