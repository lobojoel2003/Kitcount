#!/usr/bin/env node
// Copies the YAML report templates from /templates into the app bundle as
// strings. The app parses and validates them at runtime with the same code
// that validates imported template files.
//
//   node scripts/bundle-templates.mjs          # write src/core/reports/bundled-templates.ts
//   node scripts/bundle-templates.mjs --check  # fail if the file is out of date (CI)
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const templatesDir = join(here, '..', '..', 'templates');
const outFile = join(here, '..', 'src', 'core', 'reports', 'bundled-templates.ts');

const files = readdirSync(templatesDir)
  .filter((f) => f.endsWith('.yaml'))
  .sort();

const entries = files.map((f) => {
  const text = readFileSync(join(templatesDir, f), 'utf8').replace(/\r\n/g, '\n');
  return `  ${JSON.stringify(f)}: ${JSON.stringify(text)},`;
});

const output = `// AUTO-GENERATED by scripts/bundle-templates.mjs from /templates. Do not edit.
// Run \`npm run templates\` after changing a template.

export const BUNDLED_TEMPLATES: Record<string, string> = {
${entries.join('\n')}
};
`;

if (process.argv.includes('--check')) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== output) {
    console.error('src/core/reports/bundled-templates.ts is out of date. Run `npm run templates` and commit the result.');
    process.exit(1);
  }
  console.log(`Bundled templates are up to date (${files.length} files).`);
} else {
  writeFileSync(outFile, output);
  console.log(`Wrote ${files.length} templates to src/core/reports/bundled-templates.ts`);
}
